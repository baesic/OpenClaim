#!/usr/bin/env python3
"""Generate the standalone Skill reference from the public Rust/WASM data source."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
guide = json.loads((root / "data/kr-response-guide.json").read_text())
target = root / "skills/openclaim/references/response-guide.md"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
lines = ["# 개인정보 피해 대응안 — KR", "", "<!-- Generated by scripts/sync-guidance.py; edit data/kr-response-guide.json. -->", "", f"기준일: {guide['as_of']} · 재검토 예정: {guide['review_due']}", "", guide["notice"], "", guide["privacy"], "", guide["cost_policy"], "", "## 공개 상황 선택", ""]
for scenario in guide["scenarios"]:
    lines += [f"- `{scenario['id']}`: {scenario['title']}"]
for scenario in guide["scenarios"]:
    lines += ["", f"## {scenario['id']} — {scenario['title']}", "", scenario["summary"], "", f"긴급도: {scenario['urgency']} · 양식: `{scenario['template_kind']}`", "", "선택할 수 있는 대응:", ""]
    for action in scenario["actions"]:
        lines += [f"- **{action['title']}**: {action['detail']} 창구: {', '.join(action['route_ids'])}. 근거: {', '.join(action['source_ids'])}."]
    for title, key in [("로컬 증빙", "evidence"), ("요청할 수 있는 내용", "suggested_requests"), ("한계", "cautions")]:
        lines += ["", f"{title}:", ""] + [f"- {item}" for item in scenario[key]]
lines += ["", "## 기관별 대응·신청 경로", ""]
for route in guide["routes"]:
    lines += [f"### {route['id']} — {route['title']}", "", route["purpose"], ""]
    if route["url"]:
        lines += [f"[공식 안내]({route['url']})", ""]
    lines += [f"- {step}" for step in route["how_to"]]
    lines += ["", "준비: " + " · ".join(route["prepare"]), "", "비용: " + route["cost"], "", "한계: " + route["limits"], "", "근거: " + ", ".join(route["source_ids"]), ""]
lines += ["## 공개 공지별 추가 선택", ""]
for incident in guide["incidents"]:
    lines += [f"### {incident['id']} — {incident['title']}", "", incident["public_summary"], ""]
    lines += [f"- {item}" for item in incident["user_choices"] + incident["cautions"]]
    lines += ["", "창구: " + ", ".join(incident["route_ids"]), "", "근거: " + ", ".join(incident["source_ids"]), ""]
lines += ["## 공식 근거 원장", ""]
for source in guide["sources"]:
    lines += [f"- `{source['id']}`: [{source['title']}]({source['url']}) — {source['checked_on']} 확인, {source['verification']}. {source['supports']}"]
content = "\n".join(lines) + "\n"
if args.check:
    if not target.exists() or target.read_text() != content:
        raise SystemExit("Skill guidance is out of sync. Run python3 scripts/sync-guidance.py")
    print("Skill and MCP guidance content: synchronized")
else:
    target.write_text(content)
    print("Generated standalone Skill response guide")
